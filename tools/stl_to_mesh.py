# STL -> the game's compact mesh (assets/meshes/<key>.json), then src/meshes.js is rebuilt from every file there.
#   python3 tools/stl_to_mesh.py canopy in.stl key "Name" lx ly rx ry fx fy     (STL x,y of the left, right and front holes; z up)
#   python3 tools/stl_to_mesh.py frame  in.stl key "Name" [target_triangles]     (centred; STL lies ring-side down, so it is flipped)
# Vertices are int16 hundredths of a millimetre in game axes (x right, y up, z back, front = -z).
#   canopy: origin = middle of the side holes, y = 0 at the bottom of the tabs, scaled so the holes sit on the Air65 frame's posts (17.8 mm out; other frames scale it at run time)
#   frame:  origin = centre, y = 0 at the TOP face (ring tops and post tops); everything else hangs below it
import sys, struct, base64, json, glob, os
import numpy as np
kind, f, key, name = sys.argv[1:5]; root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
b = open(f, 'rb').read(); n = struct.unpack('<I', b[80:84])[0]
T = np.frombuffer(b[84:84 + n * 50], dtype=np.dtype([('n', '<3f4'), ('v', '<9f4'), ('a', '<u2')])); V = T['v'].reshape(-1, 3).astype(float)
meta = {}
if kind == 'canopy':
    lx, ly, rx, ry, fx, fy = map(float, sys.argv[5:11]); cx, cy = (lx + rx) / 2, (ly + ry) / 2; s = 35.6 / np.hypot(rx - lx, ry - ly); fs = -np.sign(fy - cy)
    G = np.stack([(V[:, 0] - cx) * s, (V[:, 2] - V[:, 2].min()) * s, (V[:, 1] - cy) * s * fs], axis=1); flip = fs > 0   # (x, z, y) is a mirror unless y was negated
    meta = {'scale': round(float(s), 4)}
else:
    cx, cy = (V[:, 0].min() + V[:, 0].max()) / 2, (V[:, 1].min() + V[:, 1].max()) / 2
    G = np.stack([V[:, 0] - cx, -(V[:, 2] - V[:, 2].min()), V[:, 1] - cy], axis=1); flip = False   # a rotation: winding stays
u, inv = np.unique(np.round(G, 3), axis=0, return_inverse=True); tri = inv.reshape(-1, 3)
target = int(sys.argv[5]) if kind == 'frame' and len(sys.argv) > 5 else 0
if target and len(tri) > target:
    import fast_simplification
    u, tri = fast_simplification.simplify(u.astype(np.float32), tri.astype(np.int32), target_count=target); u = np.asarray(u, dtype=float); tri = np.asarray(tri)
q = np.round(u * 100).astype(np.int32); uq, inv2 = np.unique(q, axis=0, return_inverse=True); tri = inv2[tri]
if flip: tri = tri[:, [0, 2, 1]]
tri = tri[(tri[:, 0] != tri[:, 1]) & (tri[:, 1] != tri[:, 2]) & (tri[:, 0] != tri[:, 2])]
assert np.abs(uq).max() < 32767 and len(uq) < 65536
out = {'name': name, 'kind': kind, 'verts': len(uq), 'tris': len(tri), **meta, 'v': base64.b64encode(uq.astype('<i2').tobytes()).decode(), 'i': base64.b64encode(tri.astype('<u2').tobytes()).decode()}
json.dump(out, open(os.path.join(root, 'assets', 'meshes', key + '.json'), 'w'))
sys.stderr.write('%s: %d verts, %d tris, mm %s .. %s\n' % (key, len(uq), len(tri), (uq.min(0) / 100).round(1), (uq.max(0) / 100).round(1)))
allm = {os.path.basename(p)[:-5]: json.load(open(p)) for p in sorted(glob.glob(os.path.join(root, 'assets', 'meshes', '*.json')))}
